export type MessageKey = keyof Messages;

let messages: Messages = en;
let language = "en";

/** Chooses the catalog for a BCP 47 tag, such as "fr-FR"; English for any other language. */
export function setLocale(locale: string): void {
  language = locale;
  messages = locale.toLowerCase().split("-")[0] === "fr" ? fr : en;
}

/** The BCP 47 tag the View formats dates with. */
export const currentLocale = (): string => language;

/** The message in the current language, with each `{name}` replaced by its value. */
export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  return messages[key].replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

type PluralKey = MessageKey extends infer K ? (K extends `${infer Base}_one` ? Base : never) : never;

/** A message with a plural form (`<key>_one`, `<key>_other`) chosen by the current language's plural rules for `count`. */
export function tn(key: PluralKey, count: number, values: Record<string, string | number> = {}): string {
  const form = new Intl.PluralRules(language).select(count) === "one" ? "one" : "other";
  return t(`${key}_${form}` as MessageKey, { ...values, count });
}

/** The read-aloud announcements in `language` ("en" or "fr"), whatever the interface language (docs/spec/read-aloud.md, rule 7). */
export function readingLabels(language: "en" | "fr"): ReadingLabels {
  const catalog = language === "fr" ? fr : en;
  return { code: catalog.readingCode, table: catalog.readingTable, diagram: catalog.readingDiagram, image: catalog.readingImage, imageNoAlt: catalog.readingImageNoAlt };
}
