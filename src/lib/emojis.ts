const plain = (text: string) => text.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();

/** The emojis whose words contain `query` (trimmed, lowercase, accents ignored); every emoji when the query has fewer than 2 characters. */
export function searchEmojis(query: string): EmojiEntry[] {
  const needle = plain(query.trim());
  const all = EMOJI_GROUPS.flatMap((group) => group.emojis);
  return needle.length < 2 ? [...all] : all.filter((each) => plain(each.t).includes(needle));
}
